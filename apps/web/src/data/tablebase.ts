/**
 * Shared dev-mode warning for the QUA-417 composite-key bug class.
 * No-op in production.
 */
function warnMalformedRecordId(
  fn: string,
  recordType: string,
  recordId: string,
): void {
  if (process.env.NODE_ENV !== "production") {
    // eslint-disable-next-line no-console
    console.warn(
      `[sourcing] ${fn}(${JSON.stringify(recordType)}, ${JSON.stringify(recordId)}): ` +
        `recordId failed isCandidateRecordId guard (likely a composite React key — see QUA-417). ` +
        `Returning null; the verdict lookup would have silently missed anyway.`,
    );
  }
}

/**
 * Get the sourcing verdict for a specific record.
 *
 * QUA-423: runtime guard against composite React keys passed as recordId
 * (the QUA-417 bug shape). Returns null fast + dev-mode warning pointing at
 * the real fix, rather than silently missing the lookup and returning null
 * for a different reason.
 */
export function getRecordVerdict(recordType: string, recordId: string): RecordVerdict | null {
  if (!isCandidateRecordId(recordId)) {
    warnMalformedRecordId("getRecordVerdict", recordType, recordId);
    return null;
  }
  return getRecordVerdicts()[`${recordType}:${recordId}`] ?? null;
}

/**
 * Get the sourcing verdict for a specific field of a record.
 * Returns null if no per-field verdict exists for this field.
 *
 * QUA-423: same composite-key guard as getRecordVerdict.
 */
export function getFieldVerdict(recordType: string, recordId: string, fieldName: string): RecordVerdict | null {
  if (!isCandidateRecordId(recordId)) {
    warnMalformedRecordId("getFieldVerdict", recordType, recordId);
    return null;
  }
  return getRecordVerdicts()[`${recordType}:${recordId}:${fieldName}`] ?? null;
}

/** Get all per-field verdicts for a specific record.
 * Returns a map of fieldName -> RecordVerdict. */
export function getFieldVerdicts(recordType: string, recordId: string): Record<string, RecordVerdict> {
  const all = getRecordVerdicts();
  const prefix = `${recordType}:${recordId}:`;
  const result: Record<string, RecordVerdict> = {};
  for (const [key, v] of Object.entries(all)) {
    if (key.startsWith(prefix)) {
      const fieldName = key.slice(prefix.length);
      result[fieldName] = v;
    }
  }
  return result;
}

export type RecordVerdictStats = {
  total: number;
} & Record<SourcingVerdictType, number>;

const VALID_VERDICT_KEYS: ReadonlySet<string> = new Set<SourcingVerdictType>([
  "confirmed",
  "contradicted",
  "unverifiable",
  "outdated",
  "partial",
  "unchecked",
]);

function emptyVerdictStats(): RecordVerdictStats {
  return { total: 0, confirmed: 0, contradicted: 0, unverifiable: 0, outdated: 0, partial: 0, unchecked: 0 };
}

/** Get sourcing stats for a specific record type */
export function getRecordVerdictStats(recordType: string): RecordVerdictStats {
  const verdicts = getRecordVerdicts();
  const stats = emptyVerdictStats();
  for (const [key, v] of Object.entries(verdicts)) {
    if (!key.startsWith(`${recordType}:`)) continue;
    // Per-field entries are three-segment keys ("grant:g_abc:amount") — skip.
    if (key.split(":").length > 2) continue;
    stats.total++;
    if (VALID_VERDICT_KEYS.has(v.verdict)) {
      stats[v.verdict as SourcingVerdictType]++;
    }
  }
  return stats;
}

/**
 * Sourcing stats restricted to a caller-supplied set of record IDs.
 *
 * Use this when the directory page deduplicates or filters records before
 * rendering, so the count of recorded verdicts cannot exceed the visible row
 * total. IDs absent from the verdict map are counted as `unchecked` so total
 * always equals `recordIds.size`. Per-field verdicts (3-segment keys) are
 * ignored.
 */
export function getRecordVerdictStatsForIds(
  recordType: string,
  recordIds: ReadonlySet<string>,
): RecordVerdictStats {
  const verdicts = getRecordVerdicts();
  const stats = emptyVerdictStats();
  for (const id of recordIds) {
    stats.total++;
    const v = verdicts[`${recordType}:${id}`];
    const verdictName: SourcingVerdictType =
      v && VALID_VERDICT_KEYS.has(v.verdict)
        ? (v.verdict as SourcingVerdictType)
        : "unchecked";
    stats[verdictName]++;
  }
  return stats;
}

