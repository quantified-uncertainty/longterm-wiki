/**
 * Pick the worst-case verdict from a list of verdict strings, ignoring any
 * values not in the canonical priority map. Pure function — exported for unit
 * tests and for any caller that has already resolved a list of verdicts.
 *
 * Routes through SOURCE_CHECK_VERDICT_PRIORITY (verdict-styles.ts) so this
 * helper and rollupVerdictFromSummary stay in sync. Per QUA-429: ordering is
 * `contradicted > outdated > partial > unverifiable > confirmed > unchecked`
 * (lower number in the priority map = worse / more actionable).
 *
 * Note: `unchecked` is included in the canonical map but is dominated by every
 * real verdict, so a list like ["confirmed", "unchecked"] still returns
 * "confirmed".
 */
export function pickWorstVerdict(
  verdicts: readonly string[],
): string | null {
  let worst: string | null = null;
  let worstPriority = Infinity;
  for (const v of verdicts) {
    const p = SOURCE_CHECK_VERDICT_PRIORITY[v];
    if (p === undefined) continue;
    if (p < worstPriority) {
      worstPriority = p;
      worst = v;
    }
  }
  return worst;
}

/**
 * Roll up per-child sourcing verdicts to a single worst-case verdict
 * string. Generic across any parent→child relationship (e.g. policy→stakeholder,
 * org→personnel, publication→citation). Callers are responsible for resolving
 * their domain-specific name→id mapping before calling this.
 *
 * This is a workaround for parent record types that lack their own
 * sourcing coverage yet (QUA-214). When coverage lands, call sites should
 * prefer the parent's own verdict and/or combine it with the aggregated
 * children via pickWorstVerdict.
 *
 * Returns null if `recordIds` is empty or none of the ids have a verdict.
 */
export function aggregateRecordVerdicts(
  recordType: string,
  recordIds: readonly string[],
): string | null {
  if (recordIds.length === 0) return null;
  const verdicts: string[] = [];
  for (const id of recordIds) {
    const v = getRecordVerdict(recordType, id);
    if (v) verdicts.push(v.verdict);
  }
  return pickWorstVerdict(verdicts);
}

