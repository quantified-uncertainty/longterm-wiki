// LOOKUP INDEXES (built lazily)
// ============================================================================

let _typedEntityIndex: Map<string, AnyEntity> | null = null;
let _entityStableIdIndex: Map<string, AnyEntity> | null = null;
let _resourceIndex: Map<string, Resource> | null = null;
let _stableIdIndex: Map<string, Resource> | null = null;
let _publicationIndex: Map<string, Publication> | null = null;
let _pageIndex: Map<string, Page> | null = null;

function typedEntityIndex() {
  if (!_typedEntityIndex) {
    _typedEntityIndex = new Map(getTypedEntities().map(e => [e.id, e]));
  }
  return _typedEntityIndex;
}

/** Lazy index: entity.stableId → entity. Covers all typed entities. */
function entityStableIdIndex(): Map<string, AnyEntity> {
  if (!_entityStableIdIndex) {
    _entityStableIdIndex = new Map();
    for (const e of getTypedEntities()) {
      if (e.stableId) {
        _entityStableIdIndex.set(e.stableId, e);
      }
    }
  }
  return _entityStableIdIndex;
}

/**
 * Get a typed entity by stableId.
 * Handles both sid_-prefixed IDs (e.g. "sid_fVMqY7vpMA") and legacy bare IDs
 * (e.g. "fVMqY7vpMA") — the latter appear in source_check_verdicts.entityId.
 */
export function getTypedEntityByStableId(stableId: string): AnyEntity | undefined {
  const registry = getIdRegistry();
  const slug = registry.byStableId?.[stableId];
  if (slug) {
    const entity = typedEntityIndex().get(slug);
    if (entity) return entity;
  }
  // Fallback: scan entities by their stableId field
  const byIndex = entityStableIdIndex().get(stableId);
  if (byIndex) return byIndex;

  // If the ID is a bare 10-char ID (no sid_ prefix), try with the prefix.
  // source_check_verdicts.entityId often stores bare IDs while entities use sid_ prefix.
  if (!isSid(stableId) && isAnySid(stableId)) {
    const prefixed = `${SID_PREFIX}${stableId}`;
    const slugP = registry.byStableId?.[prefixed];
    if (slugP) {
      const entity = typedEntityIndex().get(slugP);
      if (entity) return entity;
    }
    return entityStableIdIndex().get(prefixed);
  }

  return undefined;
}

function loadResources(): Resource[] {
  // Resources are in a separate file (split from database.json for size)
  const resourcesPath = path.join(LOCAL_DATA_DIR, "resources.json");
  try {
    return JSON.parse(fs.readFileSync(resourcesPath, "utf-8"));
  } catch {
    // Fallback to database.json if separate file doesn't exist (backward compat)
    const db = getTableBase();
    // eslint-disable-next-line @typescript-eslint/no-explicit-any -- backward compat: resources was removed from TableBaseShape
    return ((db as any).resources as Resource[]) || [];
  }
}

function resourceIndex() {
  if (!_resourceIndex) {
    const resources = loadResources();
    _resourceIndex = new Map();
    _stableIdIndex = new Map();
    for (const r of resources) {
      _resourceIndex.set(r.id, r);
      if (r.stable_id) {
        const existing = _stableIdIndex.get(r.stable_id);
        if (existing && existing.id !== r.id) {
          throw new Error(
            `Duplicate resource stable_id "${r.stable_id}" for "${existing.id}" and "${r.id}"`
          );
        }
        _stableIdIndex.set(r.stable_id, r);
      }
    }
  }
  return _resourceIndex;
}

function stableIdIndex() {
  if (!_stableIdIndex) resourceIndex(); // builds both indexes
  return _stableIdIndex!;
}

function publicationIndex() {
  if (!_publicationIndex) {
    const db = getTableBase();
    _publicationIndex = new Map(
      (db.publications || []).map((p) => [p.id, p])
    );
  }
  return _publicationIndex;
}

function pageIndex() {
  if (!_pageIndex) {
    const db = getTableBase();
    _pageIndex = new Map((db.pages || []).map((p) => [p.id, p]));
  }
  return _pageIndex;
}

