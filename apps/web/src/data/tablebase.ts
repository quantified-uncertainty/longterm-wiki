/**
 * TableBase — Core data layer: types, database loading, and basic entity lookups.
 *
 * This module is the "TableBase" layer of the wiki's Three Bases architecture:
 *   - **TableBase** (this file): Typed relational records — entities, resources,
 *     publications, experts. Source of truth: YAML files in data/entities/, data/resources/.
 *   - **FactBase** (factbase.ts): Structured triples with temporal data and provenance.
 *     Source of truth: YAML files in packages/factbase/data/fb-entities/.
 *   - **WikiBase**: Long-form prose MDX articles (content/docs/).
 *     Represented here as the `Page` interface.
 *
 * Reads database.json (generated by scripts/build-data.mjs) which contains
 * pre-transformed typedEntities. Runs at build time / server-component level only.
 *
 * This module is the foundation for all other data modules.
 * Consumers should import from "@/data" (index.ts) for backward compatibility.
 *
 * See: content/docs/internal/data-architecture.mdx for the full naming guide.
 */

