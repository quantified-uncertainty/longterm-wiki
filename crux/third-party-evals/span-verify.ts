/**
 * Span verification for third-party evaluation extractions (QUA-692).
 *
 * For every non-null scalar field the extractor returned, check that its
 * excerpt appears in the source text. Fields without a grounded excerpt
 * are dropped to null and logged — the hallucination guard.
 *
 * Implementation mirrors `crux/system-cards/span-verify.ts` (QUA-690) but
 * targets the smaller `ExtractedReport` shape and skips list-row
 * verification (we only verify `models_named` collectively, since the
 * resolver downstream is the real validator for individual model strings).
 */

import type { ExtractedReport } from "./extract-eval-report.ts";

export interface VerifyOptions {
  jaccardThreshold?: number;
  minExcerptChars?: number;
}

export interface FieldVerdict {
  verified: boolean;
  /** 1.0 exact, 0.9 whitespace-normalized, 0.0-1.0 Jaccard. */
  confidence: number;
  reason?: "no-excerpt" | "excerpt-too-short" | "below-threshold" | "not-found" | "skipped";
}

export interface VerifyResult {
  /** The report with unverified fields coerced to null. */
  verifiedReport: ExtractedReport;
  verdicts: Record<string, FieldVerdict>;
  /** Field names that were initially non-null but failed verification. */
  droppedFields: string[];
  /** Field names whose excerpt was missing entirely. */
  ungroundedFields: string[];
  /** Rounded per-field confidence — written to extraction_confidence jsonb. */
  confidenceMap: Record<string, number>;
}

// ---------------------------------------------------------------------------
// Text normalization helpers
// ---------------------------------------------------------------------------

function normalize(s: string): string {
  return s.toLowerCase().replace(/\s+/g, " ").trim();
}

function tokenize(s: string): string[] {
  return s
    .toLowerCase()
    .split(/[^\w.]+/)
    .filter((t) => t.length > 1);
}

function jaccard(a: string[], b: string[]): number {
  if (a.length === 0 || b.length === 0) return 0;
  const setA = new Set(a);
  const setB = new Set(b);
  let intersect = 0;
  for (const t of setA) if (setB.has(t)) intersect++;
  const union = setA.size + setB.size - intersect;
  return union === 0 ? 0 : intersect / union;
}

export function verifyExcerpt(
  excerpt: string,
  sourceText: string,
  options: VerifyOptions = {},
): FieldVerdict {
  const { jaccardThreshold = 0.7, minExcerptChars = 8 } = options;

  if (!excerpt || excerpt.trim().length === 0) {
    return { verified: false, confidence: 0, reason: "no-excerpt" };
  }
  if (excerpt.length < minExcerptChars) {
    return { verified: false, confidence: 0, reason: "excerpt-too-short" };
  }

  if (sourceText.toLowerCase().includes(excerpt.toLowerCase())) {
    return { verified: true, confidence: 1 };
  }

  const normExcerpt = normalize(excerpt);
  const normSource = normalize(sourceText);
  if (normSource.includes(normExcerpt)) {
    return { verified: true, confidence: 0.9 };
  }

  const excerptTokens = tokenize(excerpt);
  if (excerptTokens.length < 3) {
    return { verified: false, confidence: 0, reason: "excerpt-too-short" };
  }

  const sourceTokens = tokenize(sourceText);
  const windowSize = Math.max(excerptTokens.length, 6);
  const step = Math.max(1, Math.floor(windowSize / 2));
  let best = 0;
  for (let i = 0; i + windowSize <= sourceTokens.length; i += step) {
    const window = sourceTokens.slice(i, i + windowSize);
    const sim = jaccard(excerptTokens, window);
    if (sim > best) best = sim;
    if (best >= 0.99) break;
  }

  if (best >= jaccardThreshold) {
    return { verified: true, confidence: best };
  }
  return { verified: false, confidence: best, reason: "not-found" };
}

// Fields the verifier should NOT span-check. URLs and notes are either
// generated by the LLM (notes) or wouldn't have a meaningful excerpt
// (URLs are typically anchor text, not body text).
const METADATA_FIELDS = new Set([
  "notes",
  "methodologyUrl",
  "reportPdfUrl",
]);

// Fields where verification doesn't gate inclusion. `modelsNamed` is
// validated downstream by the model resolver (which checks the names
// exist in the entity registry) — span-checking the raw list adds noise
// without adding safety.
const UNVERIFIED_FIELDS = new Set(["modelsNamed", "capabilityLevelsAssessed"]);

export function verifyExtractedReport(
  report: ExtractedReport,
  sourceText: string,
  options: VerifyOptions = {},
): VerifyResult {
  const verdicts: Record<string, FieldVerdict> = {};
  const confidenceMap: Record<string, number> = {};
  const droppedFields: string[] = [];
  const ungroundedFields: string[] = [];

  const verifiedReport: ExtractedReport = { ...report };
  const verifiedAsRec = verifiedReport as unknown as Record<string, unknown>;

  for (const [field, value] of Object.entries(report)) {
    if (field === "excerpts") continue;
    if (UNVERIFIED_FIELDS.has(field)) {
      verdicts[field] = { verified: true, confidence: 0.5, reason: "skipped" };
      confidenceMap[field] = 0.5;
      continue;
    }
    if (value == null) continue;
    if (Array.isArray(value) && value.length === 0) {
      verifiedAsRec[field] = null;
      continue;
    }
    if (METADATA_FIELDS.has(field)) {
      verdicts[field] = { verified: true, confidence: 0.5, reason: "skipped" };
      confidenceMap[field] = 0.5;
      continue;
    }

    const excerptKey = camelToSnake(field);
    const excerpt = report.excerpts[excerptKey] ?? report.excerpts[field] ?? "";
    const verdict = verifyExcerpt(excerpt, sourceText, options);
    verdicts[field] = verdict;
    confidenceMap[field] = Number(verdict.confidence.toFixed(2));

    if (!verdict.verified) {
      verifiedAsRec[field] = null;
      droppedFields.push(field);
      if (verdict.reason === "no-excerpt" || verdict.reason === "excerpt-too-short") {
        ungroundedFields.push(field);
      }
    }
  }

  return {
    verifiedReport,
    verdicts,
    droppedFields,
    ungroundedFields,
    confidenceMap,
  };
}

/** "publishedDate" → "published_date". The extractor emits snake_case excerpt keys. */
function camelToSnake(s: string): string {
  return s.replace(/[A-Z]/g, (m) => "_" + m.toLowerCase());
}
