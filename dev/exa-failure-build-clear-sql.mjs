#!/usr/bin/env node
/**
 * Build two SQL files for the bad-Exa cleanup.
 *
 * Input:  dev/exa-failure-suspect-ids.json
 *
 * Outputs:
 *   dev/exa-failure-preview.sql           — read-only. Run this first to inspect.
 *   dev/exa-failure-clear-source-urls.sql — the actual write. Has a guard that
 *                                           ABORTs the transaction if the row
 *                                           count is outside the expected
 *                                           [0..suspect-count] range.
 *
 * Per-table column map (the "source URL" column varies by table — see
 * apps/wiki-server/src/routes/sourcing/missing-sources/updates.ts):
 *   page_citations   → url
 *   publications     → url
 *   facts            → source_url
 *   funding_programs → source
 *   <others>         → source_url (default)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const INPUT = resolve(__dirname, 'exa-failure-suspect-ids.json');
const PREVIEW_OUT = resolve(__dirname, 'exa-failure-preview.sql');
const APPLY_OUT = resolve(__dirname, 'exa-failure-clear-source-urls.sql');

const URL_COLUMN_BY_TABLE = {
  page_citations: 'url',
  publications: 'url',
  facts: 'source_url',
  funding_programs: 'source',
};
const DEFAULT_URL_COLUMN = 'source_url';

const data = JSON.parse(readFileSync(INPUT, 'utf8'));

// ---------------------------------------------------------------------------
// Preview SQL — read-only, no transaction needed. Run first; eyeball results.
// ---------------------------------------------------------------------------
{
  const lines = [];
  lines.push('-- Preview the bad-Exa cleanup. READ-ONLY. No writes.');
  lines.push(`-- First failure: [${data.firstFailureIndex}/892]`);
  lines.push(`-- Scrollback covered: [${data.firstSeenInScrollback}..${data.lastIndex}]`);
  lines.push('-- Generated by: dev/exa-failure-build-clear-sql.mjs');
  lines.push('--');
  lines.push('-- Run with: psql_prod -f dev/exa-failure-preview.sql');
  lines.push('--');
  lines.push('-- For each suspect table this prints:');
  lines.push('--   suspect_count   = how many ids we plan to clear (the cap)');
  lines.push('--   rows_with_url   = how many of those currently have the URL set');
  lines.push('--                     (this is what the UPDATE will hit)');
  lines.push('--   rows_null       = how many are already NULL (UPDATE will skip these)');
  lines.push('--');
  lines.push("-- Sanity rule: rows_with_url + rows_null must equal suspect_count.");
  lines.push('-- If not, some ids do not exist in the table → investigate before applying.');
  lines.push('');

  for (const [table, ids] of Object.entries(data.tables)) {
    const col = URL_COLUMN_BY_TABLE[table] ?? DEFAULT_URL_COLUMN;
    const idList = ids.join(', ');

    lines.push(`-- ===== ${table} (${ids.length} suspect ids, column: ${col}) =====`);
    lines.push(`SELECT '${table}'::text AS tbl,`);
    lines.push(`       ${ids.length}::int AS suspect_count,`);
    lines.push(`       count(*) FILTER (WHERE ${col} IS NOT NULL) AS rows_with_url,`);
    lines.push(`       count(*) FILTER (WHERE ${col} IS NULL)     AS rows_null,`);
    lines.push(`       count(*)                                    AS rows_found`);
    lines.push(`FROM ${table}`);
    lines.push(`WHERE id IN (${idList});`);
    lines.push('');
    lines.push(`-- Show a sample of the URLs that would be cleared (up to 10):`);
    lines.push(`SELECT id, ${col}`);
    lines.push(`FROM ${table}`);
    lines.push(`WHERE id IN (${idList}) AND ${col} IS NOT NULL`);
    lines.push(`ORDER BY id LIMIT 10;`);
    lines.push('');
  }

  writeFileSync(PREVIEW_OUT, lines.join('\n'));
  console.log(`Wrote ${PREVIEW_OUT}`);
}

// ---------------------------------------------------------------------------
// Apply SQL — the UPDATE, gated by an inline sanity assertion.
// ---------------------------------------------------------------------------
{
  const lines = [];
  lines.push('-- APPLY the bad-Exa cleanup: clear source-URL columns for suspect ids.');
  lines.push(`-- First failure: [${data.firstFailureIndex}/892]`);
  lines.push(`-- Scrollback covered: [${data.firstSeenInScrollback}..${data.lastIndex}]`);
  lines.push('-- Generated by: dev/exa-failure-build-clear-sql.mjs');
  lines.push('--');
  lines.push('-- Pre-flight: run dev/exa-failure-preview.sql FIRST and confirm');
  lines.push('-- the numbers look right. Only then run this file.');
  lines.push('--');
  lines.push('-- Run with: psql_prod -f dev/exa-failure-clear-source-urls.sql');
  lines.push('--');
  lines.push('-- Safety: each table block does:');
  lines.push("--   1. count rows that match (id ∈ suspects AND col IS NOT NULL)");
  lines.push('--   2. RAISE EXCEPTION if the count exceeds the suspect-cap (impossible');
  lines.push('--      under normal conditions; would mean a SQL injection / typo)');
  lines.push('--   3. UPDATE ... = NULL with the same WHERE clause, RETURNING the ids');
  lines.push('--   4. RAISE NOTICE with the actual updated count');
  lines.push('-- If any RAISE EXCEPTION fires, the entire transaction rolls back.');
  lines.push('');
  lines.push('BEGIN;');
  lines.push('');

  for (const [table, ids] of Object.entries(data.tables)) {
    const col = URL_COLUMN_BY_TABLE[table] ?? DEFAULT_URL_COLUMN;
    const idList = ids.join(', ');
    const cap = ids.length;

    lines.push(`-- ===== ${table} (cap: ${cap} ids, column: ${col}) =====`);
    lines.push('DO $$');
    lines.push('DECLARE');
    lines.push('  to_clear int;');
    lines.push('  cleared  int;');
    lines.push('BEGIN');
    lines.push(`  SELECT count(*) INTO to_clear`);
    lines.push(`  FROM ${table}`);
    lines.push(`  WHERE id IN (${idList}) AND ${col} IS NOT NULL;`);
    lines.push('');
    lines.push(`  IF to_clear > ${cap} THEN`);
    lines.push(`    RAISE EXCEPTION 'safety check: ${table} matched % rows but cap is ${cap} — aborting', to_clear;`);
    lines.push('  END IF;');
    lines.push('');
    lines.push(`  RAISE NOTICE '${table}: % rows will be cleared (cap ${cap})', to_clear;`);
    lines.push('');
    lines.push(`  UPDATE ${table}`);
    lines.push(`  SET ${col} = NULL`);
    lines.push(`  WHERE id IN (${idList})`);
    lines.push(`    AND ${col} IS NOT NULL;`);
    lines.push('');
    lines.push('  GET DIAGNOSTICS cleared = ROW_COUNT;');
    lines.push(`  RAISE NOTICE '${table}: cleared % rows', cleared;`);
    lines.push('');
    lines.push('  IF cleared <> to_clear THEN');
    lines.push(`    RAISE EXCEPTION 'safety check: planned % rows but UPDATE wrote % — aborting', to_clear, cleared;`);
    lines.push('  END IF;');
    lines.push('END $$;');
    lines.push('');
  }

  lines.push('-- All sanity checks passed. Commit.');
  lines.push('COMMIT;');
  lines.push('');

  writeFileSync(APPLY_OUT, lines.join('\n'));
  console.log(`Wrote ${APPLY_OUT}`);
}

const total = Object.values(data.tables).reduce((s, a) => s + a.length, 0);
console.log(`Tables: ${Object.keys(data.tables).join(', ')}`);
console.log(`Total suspect ids: ${total}`);
